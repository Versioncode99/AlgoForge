"""The Prop Desk: many accounts, one set of deterministic controls.

Eleven modules, arranged as one pipeline:

    Research Factory → Strategy Library → Strategy Health → Prop Account
    Compatibility → Strategy Allocation → Risk / Prop Rules Gate →
    Execution Fabric → Broker/API adapter → Account

`identity` separates provider, platform, venue, data feed and account, so a
front end is never mistaken for a place orders go. `credentials` holds the
pointer to a secret and never the secret. `instruments` maps a product to
another product with the arithmetic shown. `orders` is the event-driven order
and position lifecycle, built for events that duplicate, reorder and arrive
late. `fabric` is the one interface every provider is reached through, with a
per-credential rate budget, a priority queue and an outbox. `adapters` holds one
adapter that executes — against a local simulator, and it says so — and three
that declare their provider's real interface and refuse. `reconcile` treats the
provider as authoritative. `copy` is leader and followers, converging on net
position targets. `policy` answers what an account is *permitted* to do, four-
valued, where unknown is never permission. `allocation` chooses what runs where,
deterministically, with advice that can only narrow. `news` is scheduled
economic events from sources that permit being read. `desk` is the funnel every
order passes through, and the only path from an intent to an adapter.

Nothing here imports a broker client library, nothing here reaches a network
except the FRED calendar client, and `forge.execution.LIVE_EXECUTION_AVAILABLE`
remains `False`. No live broker execution exists in this build.
"""

